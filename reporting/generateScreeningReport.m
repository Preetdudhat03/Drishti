function report = generateScreeningReport(imageId, predictionResult, humanReviewData)
% GENERATESCREENINGREPORT Formats structured clinical screening report
%
% Syntax:
%   report = generateScreeningReport(imageId, predictionResult)
%   report = generateScreeningReport(imageId, predictionResult, humanReviewData)
%
% EyeXpert — SIH 2026

    arguments
        imageId (1,1) string
        predictionResult (1,1) struct
        humanReviewData struct = struct('Status', "PENDING", 'ClinicianId', "Unassigned", 'Notes', "Awaiting clinical review")
    end

    timestamp = string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));

    % Extract quality information
    if isfield(predictionResult, 'Quality')
        qStatus = string(predictionResult.Quality.Status);
        qScore = sprintf('%.2f', predictionResult.Quality.OverallScore);
    else
        qStatus = "UNKNOWN";
        qScore = "N/A";
    end

    % Enhancement information
    if isfield(predictionResult, 'EnhancementApplied') && predictionResult.EnhancementApplied
        enhStatus = "YES (CLAHE & Illumination Normalization Applied)";
    else
        enhStatus = "NO (Standard Direct Preprocessing)";
    end

    % DR Prediction details
    drLevelStr = sprintf('Level %d', predictionResult.PredictedLevel);
    severityStr = string(predictionResult.SeverityText);
    referableStr = string(predictionResult.ReferableText);
    modelProbStr = sprintf('%.1f%%', predictionResult.ModelProbability * 100);
    calibConfStr = sprintf('%.1f%%', predictionResult.CalibratedConfidence * 100);

    % Clinical recommendations
    recommendationStr = string(predictionResult.ClinicalRecommendation);

    % Human Validation details
    humanStatusStr = string(humanReviewData.Status);
    clinicianNotesStr = string(humanReviewData.Notes);

    % Structured Text Report
    textReport = sprintf([ ...
        '========================================================================\n' ...
        '                      EYEXPERT CLINICAL SCREENING REPORT                \n' ...
        '                   SIH 2026 AI-Assisted Telemedicine Prototype          \n' ...
        '========================================================================\n' ...
        'Image / Patient ID:    %s\n' ...
        'Report Timestamp:      %s\n' ...
        '------------------------------------------------------------------------\n' ...
        '1. IMAGE QUALITY AUDIT\n' ...
        '   Quality Status:     %s\n' ...
        '   Quality Score:      %s / 1.00\n' ...
        '   Enhancement:        %s\n' ...
        '------------------------------------------------------------------------\n' ...
        '2. AI SCREENING RESULT\n' ...
        '   DR Classification:  %s\n' ...
        '   Severity Grade:     %s\n' ...
        '   Referable DR:       %s\n' ...
        '   Model Probability:  %s (Softmax raw score)\n' ...
        '   Calibrated Conf:    %s (Temperature scaled)\n' ...
        '------------------------------------------------------------------------\n' ...
        '3. EXPLAINABILITY & EVIDENCE\n' ...
        '   AI Evidence:        Grad-CAM attention concentrated in focal retinal\n' ...
        '                       regions associated with the DR level prediction.\n' ...
        '   Clinical Action:    %s\n' ...
        '------------------------------------------------------------------------\n' ...
        '4. HUMAN-IN-THE-LOOP CLINICAL VALIDATION\n' ...
        '   Validation Status:  %s\n' ...
        '   Clinician Notes:    %s\n' ...
        '------------------------------------------------------------------------\n' ...
        'IMPORTANT CLINICAL SAFETY NOTICE:\n' ...
        'This screening report was generated by the EyeXpert prototype for\n' ...
        'clinical decision support and telemedicine triage. It is NOT an\n' ...
        'autonomous diagnostic device. Final clinical interpretation and\n' ...
        'treatment decisions REQUIRE evaluation by a qualified ophthalmologist.\n' ...
        '========================================================================\n' ...
    ], imageId, timestamp, qStatus, qScore, enhStatus, ...
       drLevelStr, severityStr, referableStr, modelProbStr, calibConfStr, ...
       recommendationStr, humanStatusStr, clinicianNotesStr);

    % Build return struct
    report = struct();
    report.ImageId = imageId;
    report.Timestamp = timestamp;
    report.QualityStatus = qStatus;
    report.QualityScore = qScore;
    report.EnhancementStatus = enhStatus;
    report.DRLevel = drLevelStr;
    report.Severity = severityStr;
    report.ReferableDR = referableStr;
    report.ModelProbability = modelProbStr;
    report.CalibratedConfidence = calibConfStr;
    report.Recommendation = recommendationStr;
    report.HumanValidationStatus = humanStatusStr;
    report.ClinicianNotes = clinicianNotesStr;
    report.TextReport = string(textReport);
    report.Disclaimer = "AI-assisted screening prototype only. Final clinical interpretation requires review by a qualified ophthalmologist or clinician.";
end
